#!/usr/bin/env node
// Generates the catalogue migration used for server-side scoring from data/*.ts.
// Run `node scripts/generate-content-seed.cjs` after editing lessons, quizzes or challenges.
const fs = require("node:fs");
const path = require("node:path");
const { load, root } = require("./ts-loader.cjs");

const OUTPUT = path.join(root, "supabase", "migrations", "20260928190100_catalog_content.sql");

const literal = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const textArray = (values) => `array[${values.map(literal).join(", ")}]::text[]`;

function buildContentSeed() {
  const { lessons } = load("data/lessons");
  const { quizzes } = load("data/quizzes");
  const { challenges } = load("data/challenges");
  const { challengeAnswers } = load("data/challenge-answers");
  const missing = challenges.filter((challenge) => !challengeAnswers[challenge.id]?.trim());
  if (missing.length) throw new Error(`Flag manquant dans data/challenge-answers.ts : ${missing.map((challenge) => challenge.id).join(", ")}`);

  const lessonRows = lessons.map((lesson) => `  (${[literal(lesson.id), literal(lesson.courseId), literal(lesson.title), lesson.xpReward].join(", ")}, 'catalog')`);
  const quizRows = quizzes.map((quiz) => `  (${[literal(quiz.id), literal(quiz.lessonId), literal(quiz.title), quiz.xpReward, textArray(quiz.questions.map((question) => question.correctAnswer))].join(", ")}, 'catalog')`);
  const challengeRows = challenges.map((challenge) => `  (${[literal(challenge.id), literal(challenge.title), challenge.xpReward, literal(challengeAnswers[challenge.id].trim())].join(", ")}, 'catalog')`);

  return `-- Generated by scripts/generate-content-seed.cjs from data/*.ts. Do not edit by hand.
-- Scoring catalogue: XP rewards, quiz answer keys and challenge flags stay server-side.

insert into private.content_lessons (id, course_id, title, xp_reward, source) values
${lessonRows.join(",\n")}
on conflict (id) do update set course_id = excluded.course_id, title = excluded.title, xp_reward = excluded.xp_reward, source = 'catalog';

insert into private.content_quizzes (id, lesson_id, title, xp_reward, correct_answers, source) values
${quizRows.join(",\n")}
on conflict (id) do update set lesson_id = excluded.lesson_id, title = excluded.title, xp_reward = excluded.xp_reward, correct_answers = excluded.correct_answers, source = 'catalog';

insert into private.content_challenges (id, title, xp_reward, expected_answer, source) values
${challengeRows.join(",\n")}
on conflict (id) do update set title = excluded.title, xp_reward = excluded.xp_reward, expected_answer = excluded.expected_answer, source = 'catalog';
`;
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT, buildContentSeed());
  console.log(`Catalogue écrit dans ${path.relative(root, OUTPUT)}`);
}

module.exports = { buildContentSeed, OUTPUT };
