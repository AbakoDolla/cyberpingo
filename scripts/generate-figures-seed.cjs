#!/usr/bin/env node
// Builds supabase/seed/12_figures.sql: replaces, in the lessons already published, each plain-text schema by the figure that
// draws it (lib/figure-spec.ts). The seeds 01 to 11 already carry the figures for a fresh database; this one brings the same
// content to a database that was seeded before the conversion.
//
// Safe by construction: a block is replaced only while it still holds, byte for byte, the text it had before the conversion
// (supabase/seed/content/figures-legacy.json, compared by md5). A lesson an administrator edited keeps its text, and running the
// seed twice changes nothing. Deploy the site BEFORE applying it: the lesson page reads both forms, so the order never shows
// raw JSON to a learner.
// Run `node scripts/generate-figures-seed.cjs` after editing any figure.
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { root } = require("./ts-loader.cjs");
const { createSupabaseDatabase } = require("./pglite-supabase.cjs");

const OUTPUT = path.join(root, "supabase", "seed", "12_figures.sql");
const LEGACY_FILE = path.join(root, "supabase", "seed", "content", "figures-legacy.json");

const md5 = (text) => crypto.createHash("md5").update(text, "utf8").digest("hex");
const literal = (value) => `'${String(value).replace(/'/g, "''")}'`;

async function build() {
  const legacy = JSON.parse(fs.readFileSync(LEGACY_FILE, "utf8"));
  const db = await createSupabaseDatabase({ seed: true, seedFilter: (name) => !name.startsWith("12_") });
  const statements = [];
  const kinds = {};
  let lessons = 0;
  try {
    const { rows } = await db.query("select id, content from public.lessons order by id");
    const content = new Map(rows.map((row) => [row.id, row.content.blocks]));
    for (const [lessonId, blocks] of Object.entries(legacy)) {
      const stored = content.get(lessonId);
      if (!stored) throw new Error(`Leçon ${lessonId} introuvable : figures-legacy.json est périmé.`);
      lessons += 1;
      for (const [indexText, old] of Object.entries(blocks)) {
        const index = Number(indexText);
        const block = stored[index];
        if (!block || block.type !== "schema") throw new Error(`Leçon ${lessonId} : le bloc ${index} n’est plus un schéma.`);
        if (!block.content.trim().startsWith("{")) throw new Error(`Leçon ${lessonId} : le bloc ${index} n’a pas été converti en figure.`);
        const kind = JSON.parse(block.content).kind;
        kinds[kind] = (kinds[kind] ?? 0) + 1;
        statements.push(
          `update public.lessons set content = jsonb_set(content, '{blocks,${index},content}', to_jsonb(${literal(block.content)}::text))\n`
          + `where id = ${literal(lessonId)} and content #>> '{blocks,${index},type}' = 'schema' and md5(content #>> '{blocks,${index},content}') = '${md5(old)}';`,
        );
      }
    }
  } finally {
    await db.close();
  }
  const summary = Object.entries(kinds).sort((a, b) => b[1] - a[1]).map(([kind, n]) => `${kind} ${n}`).join(", ");
  return [
    "-- Generated by scripts/generate-figures-seed.cjs from the figures of supabase/seed/content/*.ts. Do not edit by hand.",
    `-- CyberPingo figures: ${statements.length} plain-text schemas of ${lessons} lessons redrawn as figures (${summary}).`,
    "-- Guarded and idempotent: a schema is replaced only while it still holds the exact text it had before the conversion",
    "-- (md5 of supabase/seed/content/figures-legacy.json), so nothing an administrator edited is overwritten.",
    "-- Apply it after the site that draws figures is deployed.",
    "",
    "begin;",
    "",
    statements.join("\n"),
    "",
    "commit;",
    "",
  ].join("\n");
}

if (require.main === module) {
  build().then((sql) => {
    fs.writeFileSync(OUTPUT, sql);
    console.log(`Seed des figures écrit dans ${path.relative(root, OUTPUT)} (${Math.round(sql.length / 1024)} Ko)`);
  }).catch((error) => { console.error(error.message); process.exit(1); });
}

module.exports = { build, OUTPUT, md5 };
